"""Writes Calco/es.lproj/Localizable.strings from scripts/l10n/es.py, checking it against the
strings the app uses.

    xcodebuild ... -derivedDataPath build/dd-loc SWIFT_EMIT_LOC_STRINGS=YES build
    python3 scripts/l10n/localize.py

Fails on missing translations and on placeholders (%@, %lld) that don't match.
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
namespace = {}
exec(open(os.path.join(ROOT, "scripts/l10n/es.py"), encoding="utf-8").read(), namespace)
ES = namespace["ES"]

keys = set()
for f in glob.glob(os.path.join(ROOT, "build/dd-loc/Build/Intermediates.noindex/Calco.build/**/*.stringsdata"), recursive=True):
    for entries in json.load(open(f)).get("tables", {}).values():
        keys.update(e["key"] for e in entries)
if not keys:
    sys.exit("No extracted strings: build with SWIFT_EMIT_LOC_STRINGS=YES into build/dd-loc first.")

UNTRANSLATED = {"", "%lld", "%lld / %lld", "%lld px", "%lld × %lld px", "%lld%%", "%lld×", "½×"}
missing = sorted(k for k in keys if k not in ES and k not in UNTRANSLATED)
spec = re.compile(r"%(?:lld|@|%)")
mismatched = sorted(k for k, v in ES.items() if spec.findall(k) != spec.findall(v))
if missing or mismatched:
    for k in missing:
        print("missing:", k)
    for k in mismatched:
        print("placeholders differ:", k)
    sys.exit(1)

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

lines = ["/* Spanish. Keys are the English text; generated by scripts/l10n/localize.py. */", ""]
lines += [f'"{esc(k)}" = "{esc(ES[k])}";' for k in sorted(keys) if k in ES]
open(os.path.join(ROOT, "Calco/es.lproj/Localizable.strings"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
unused = sorted(set(ES) - keys)
print(f"wrote {len(lines) - 2} strings" + (f"; {len(unused)} unused: {unused}" if unused else ""))
